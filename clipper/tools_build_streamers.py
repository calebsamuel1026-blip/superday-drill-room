"""Builds config/streamers.yaml (persona knowledge base) from data/research/streamers_research.yaml.
Re-run after editing the research file. Hand-edits belong in config/streamers_overrides.yaml."""
import re, yaml
from pathlib import Path
R = Path(__file__).parent
res = yaml.safe_load(open(R / "data/research/streamers_research.yaml"))
ov_path = R / "config/streamers_overrides.yaml"
overrides = (yaml.safe_load(ov_path.read_text()) if ov_path.exists() else {}) or {}
URL = {"twitch": "https://www.twitch.tv/{}", "kick": "https://kick.com/{}", "youtube": "https://www.youtube.com/{}"}
out = []
for lang in ("en", "es", "pt"):
    for c in res[lang]:
        sid = re.sub(r"[^a-z0-9]+", "_", c["name"].lower()).strip("_")
        handles, channels = {}, {}
        for plat, h in (c.get("handles") or {}).items():
            h = str(h)
            if not h or h.lower().startswith(("unverified", "none")) or "," in h or " / " in h:
                continue
            h = h.replace("(unverified)", "").strip()
            handles[plat] = h
            if plat in URL:
                base = URL[plat].format(h if plat != "youtube" else (h if h.startswith("@") else "@" + h))
                channels[plat] = base + ("/videos?filter=archives&sort=time" if plat == "twitch"
                                         else "/streams" if plat == "youtube" else "/videos" if plat == "kick" else "")
        entry = {
            "id": sid, "name": c["name"], "language": lang, "priority": int(c.get("virality_score") or 5),
            "handles": handles, "channels": channels,
            "persona": c.get("persona"), "viral_moment_types": c.get("viral_moment_types"),
            "catchphrases": c.get("catchphrases"), "gta_history": c.get("gta_history"),
            "gta6_plans": c.get("gta6_announced"), "clipping_program": c.get("clipping_program"),
            "notes": c.get("notes"),
            "facecam": None,  # e.g. {x: 0.0, y: 0.0, w: 0.25, h: 0.3} as fractions of the frame
        }
        entry.update(overrides.get(sid, {}))
        out.append(entry)
(R / "config/streamers.yaml").write_text(
    "# GENERATED by tools_build_streamers.py — edit data/research/streamers_research.yaml or\n"
    "# config/streamers_overrides.yaml, then re-run.\n" + yaml.safe_dump({"streamers": out}, allow_unicode=True, sort_keys=False, width=110))
print(len(out), "streamers")
